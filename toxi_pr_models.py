"""toxi_pr_models.py -- precision/recall-vs-threshold 2x2 for NON-XGBoost classifiers.

Same toxicity data + same figure layout as the XGBoost reference `toxi_pr.png`
(regenerated by `toxi_pr_all.py`), but with the classifier swapped out.

Layout (identical to toxi_pr.png):
    rows : top = Precision vs threshold ; bottom = Recall vs threshold
    cols : left  = EN model on EN test
           right = EN model on IT test  AND  IT model on IT test
    x-axis threshold 0..1 ; EuroBERT-210m = SOLID ; EuroBERT-610m = DOTTED ;
    the F1-optimal val threshold is marked.

Data / features (DELIBERATE choice -- see note):
    * data = data/toxi_clean/{en,it}_{train,validation,test}.parquet  (label is_toxic)
    * emb  = emb_bf16/toxic/{210m,610m}/emb_<lang>_<split>.npy        (mean pooled, float32)
    * features = the RAW mean embeddings, NO perlang_z / no z-scoring / no L2-norm.
      Rationale (stated as required): keeps the exact "raw features" convention of the
      fine-tune comparison and is the simplest honest pipeline.  perlang_z is a
      language-specific transform; this script instead compares models purely on the raw
      frozen backbone.  (The XGBoost reference `toxi_pr_all.py` DID use perlang_z, so the
      absolute numbers here are not meant to be bit-comparable to toxi_pr.png -- the point
      is the cross-lingual *shape* per classifier.)

Classifiers (per backbone, per language: fit on <lang>_train, score <lang>_test):
    SVC_linear, MLPClassifier, LogisticRegression, RandomForestClassifier,
    KNeighborsClassifier, GaussianNB

Scoring (consistency + threshold transferability):
    * predict_proba(X)[:, 1]  for every classifier that has it (MLP / LogReg / RF / KNN / GNB).
    * SVC_linear -> sigmoid(decision_function(X)) in [0, 1] (monotone, data-independent, so a
      val-tuned threshold transfers to test).  NOTE: plain libsvm `SVC(kernel='linear')` is
      INFEASIBLE at this scale -- measured >11 min/fit and non-convergence on n=24k x 768,
      with cache_size=2000.  We therefore use its standard fast equivalent, the liblinear
      PRIMAL linear SVM `LinearSVC(loss='squared_hinge', dual=False)` (fits in ~28 s, 26
      iters, full training split).  We do NOT use SVC(probability=True) (5-fold Platt CV)
      and do NOT rank-normalise (rank normalisation is sample-dependent -> val threshold
      would not transfer to test).

Val-tuned threshold = F1-optimal on the model's OWN-language validation split
(grid 0.00..1.00 step 0.01), same rule as `models_toxi/manifest.json` / `toxi_pr_all.py`.

Outputs (CREATE-only; our own outputs are re-written by design):
    toxi_pr_<model>.png            -- per-model 2x2 (210 solid / 610 dotted)
    toxi_pr_models_grid.png        -- combined grid: rows=models, cols={210m,610m}, F1-vs-thr
    toxi_pr_models.json / .md      -- numbers (P@R90 for EN-on-IT & IT-on-IT, AUC, full sweeps)

Constraints: mean only; CPU (n_jobs=2); no GPU; no windows; no file deleted or moved.

Usage:
    python toxi_pr_models.py                 # foreground full run (both backbones, all models)
    python toxi_pr_models.py --launch        # detached hidden via launch_hidden.vbs
    python toxi_pr_models.py --smoke         # tiny plumbing check (TEMP outputs)
    python toxi_pr_models.py --only SVC_linear,MLPClassifier
    python toxi_pr_models.py --backbone 210m
"""
