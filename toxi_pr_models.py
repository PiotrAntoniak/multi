"""toxi_pr_models.py -- precision/recall vs decision-score-percentile 2x2 for NON-XGBoost classifiers.

Same toxicity data as the XGBoost reference `toxi_pr.png` (regenerated by `toxi_pr_all.py`),
but with the classifier swapped out.  Same figure layout as the XGBoost reference:

    rows : top = Precision vs axis ; bottom = Recall vs axis
    cols : left  = EN model on EN test
           right = EN model on IT test  AND  IT model on IT test
    EuroBERT-210m = SOLID ; EuroBERT-610m = DOTTED ; val-tuned threshold marked.

WHY THE SWEEP AXIS IS A PERCENTILE (not raw probability 0..1) -- diagnosis + fix
-------------------------------------------------------------------------------
The previous version scored EVERY classifier with `predict_proba(X)[:, 1]` and swept a fixed
raw threshold grid 0.00..1.00 step 0.01.  For several classifiers that score is DEGENERATE as a
sweep axis and made the whole comparison meaningless:

  * GaussianNB: `predict_proba` saturates.  Measured on 210m/EN-test: 62.8% of points have
    p < 1e-6 and 16.4% have p > 1-1e-6.  The F1-optimal VALIDATION threshold landed at 1.00
    (210m EN) / 0.99 (610m EN) / 1.00 (610m IT) -- i.e. on the extreme tip of the axis -- and the
    P/R curves were essentially flat except for a single jump between t=0.00 and t=0.01.
  * KNeighborsClassifier (k=5): `predict_proba` takes only k+1 = 6 discrete values
    {0, .2, .4, .6, .8, 1}.  A "threshold sweep" over 0..1 is therefore a 6-step staircase, not a
    continuous axis (the val-F1 optimum even landed at t=0.21 -- an artifact of picking the first
    grid point above a plateau).

THE FIX: give every model a MONOTONE, CONTINUOUS decision score, and sweep the score's
PERCENTILES (q = 0..100) instead of a raw 0..1 grid.  The percentile axis is unit-free, continuous,
monotone, and directly comparable across classifiers and backbones (q = % of the test points whose
score is below the threshold; q=0 predicts everything positive, larger q = stricter).

Per-model decision score (higher score = more toxic, all monotone):
  * XGBoost             -> `predict_proba[:,1]` (binary:logistic; fully continuous here:
                           measured 2310 distinct values on the IT test).  Same recipe as the
                           reference `toxi_pr_all.py` (hist, max_bin=64, cpu, depth=8, mcw=5,
                           lr=0.1, n=400).  Listed FIRST in the model order.
  * SVC_linear          -> `decision_function` (liblinear primal linear SVM margin).
  * LogisticRegression  -> `decision_function` (logit).
  * MLPClassifier       -> `predict_proba[:,1]` (continuous).
  * RandomForestClassifier -> `predict_proba[:,1]` (200 trees: continuous to ~1/200).
  * GaussianNB          -> log-likelihood-ratio `predict_log_proba[:,1] - predict_log_proba[:,0]`
                           (monotone with the saturated probability, but NOT saturated itself:
                           measured spread ~302 nats on 210m/EN-test).
  * KNeighborsClassifier -> CONTINUOUS distance-weighted positive fraction:
                           sum_{i in kNN, y_i=1} 1/(d_i+eps) / sum_{i in kNN} 1/(d_i+eps)
                           (a standard continuous refinement of the discrete k=5 fraction:
                           measured 1226 distinct values vs 6 before).

Ranking-based metrics (AUC, precision@recall=0.90) are invariant to monotone rescaling, so for
every model EXCEPT KNN (whose score function genuinely changed) those numbers are unchanged from
the old run; for KNN they are recomputed on the new continuous score.

Scoring note for SVC_linear: plain libsvm `SVC(kernel='linear')` is INFEASIBLE at this scale
(measured >11 min/fit, non-convergent on n=24k x 768).  We use its standard fast equivalent, the
liblinear PRIMAL linear SVM `LinearSVC(loss='squared_hinge', dual=False)` (~29 s/fit).

Data / features (DELIBERATE choice): data = data/toxi_clean/{en,it}_{train,validation,test}.parquet
(label is_toxic); emb = emb_bf16/toxic/{210m,610m}/emb_<lang>_<split>.npy (mean pooled, float32);
features = the RAW mean embeddings, NO perlang_z / no z-scoring / no L2-norm.

Val-tuned threshold = F1-optimal on the model's OWN-language validation split, searched over the
validation score's percentiles (raw thresholds are unbounded for margin/LLR scores, so a fixed
0..1 grid cannot be used); the chosen raw threshold is then located on each test cell's own
percentile axis.

Combined grid figure (THE deliverable, rows = classifier x {Precision, Recall}, cols = backbone):
`toxi_pr_models_grid.png` is ONE big grid: for each classifier TWO rows (Precision, Recall), two
columns (210m, 610m), each panel overlaying the three language pairs vs the decision-score
percentile with the val-tuned threshold marker.  Two metric-only grids
(`toxi_pr_models_grid_precision.png`, `toxi_pr_models_grid_recall.png`) are also emitted for
convenience.  Never F1.  Because the columns already separate the backbones, a within-cell
solid/dotted styling would be meaningless, so the grid columns are labelled with the backbone name
only; the solid-vs-dotted (210m vs 610m) distinction lives in the per-model figures.

Outputs (CREATE-only; our own outputs are re-written by design):
    toxi_pr_<model>.png                    -- per-model 2x2 (210 solid / 610 dotted), P top / R bottom
    toxi_pr_models_grid.png                -- ONE combined grid: rows=classifier x {P,R}, cols=backbone
    toxi_pr_models_grid_precision.png      -- grid: rows=models, cols={210m,610m}, Precision vs percentile
    toxi_pr_models_grid_recall.png         -- grid: rows=models, cols={210m,610m}, Recall vs percentile
    toxi_pr_models.json / .md              -- numbers (P@R90 for EN-on-IT & IT-on-IT, AUC, full sweeps)

Constraints: mean only; CPU (n_jobs=2); no GPU; no windows; no file deleted or moved.

Usage:
    python toxi_pr_models.py                 # foreground full run (both backbones, all models)
    python toxi_pr_models.py --launch        # detached hidden via launch_hidden.vbs
    python toxi_pr_models.py --smoke         # tiny plumbing check (TEMP outputs)
    python toxi_pr_models.py --only SVC_linear,MLPClassifier
    python toxi_pr_models.py --backbone 210m
"""
