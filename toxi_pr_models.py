# ------------------------------------------------------------------ decision scores
def decision_score(clf, X, kind, ytr=None):
    """Monotone, continuous toxicity score (higher = more toxic), per classifier kind."""
    if kind == "proba":
        return np.asarray(clf.predict_proba(X), dtype=np.float64)[:, 1]
    if kind == "margin":
        return np.asarray(clf.decision_function(X), dtype=np.float64).ravel()
    if kind == "gnb_llr":
        lp = np.asarray(clf.predict_log_proba(X), dtype=np.float64)
        return lp[:, 1] - lp[:, 0]
    if kind == "knn_dist":
        ytr = np.asarray(ytr, dtype=np.int64)
        k = int(getattr(clf, "n_neighbors", 5))
        d, idx = clf.kneighbors(X, n_neighbors=k)
        w = 1.0 / (np.asarray(d, dtype=np.float64) + 1e-6)
        yn = (ytr[np.asarray(idx)] == 1).astype(np.float64)
        return (w * yn).sum(1) / w.sum(1)
    raise ValueError("unknown score kind %r" % (kind,))


def metrics_at(y, s, thr):
    y = np.asarray(y, dtype=np.int64)
    pred = (np.asarray(s, dtype=np.float64) >= thr).astype(np.int64)
    tp = int(((pred == 1) & (y == 1)).sum())
    fp = int(((pred == 1) & (y == 0)).sum())
    fn = int(((pred == 0) & (y == 1)).sum())
    tn = int(((pred == 0) & (y == 0)).sum())
    prec = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    rec = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2.0 * prec * rec / (prec + rec) if (prec + rec) > 0 else 0.0
    return {"threshold": float(thr), "precision": float(prec), "recall": float(rec),
            "f1": float(f1), "TP": tp, "FP": fp, "FN": fn, "TN": tn}


def auc_at(y, s):
    from sklearn.metrics import roc_auc_score
    y = np.asarray(y, dtype=np.int64)
    if y.sum() == 0 or y.sum() == len(y):
        return None
    return float(roc_auc_score(y, s))


def f1_opt_threshold(y, s):
    """F1-optimal raw score threshold, searched over the score's OWN percentiles.

    Works for unbounded scores (margin / LLR) where a fixed 0..1 grid is invalid."""
    from sklearn.metrics import f1_score
    best_t, best_f, best_q = float(np.median(s)), -1.0, 50
    for q in QS:
        t = float(np.percentile(s, q))
        f = f1_score(y, (s >= t).astype(int), zero_division=0)
        if f > best_f:
            best_f, best_t, best_q = float(f), t, int(q)
    return best_t, best_q


def at_recall(y, s, target=RECALL_TARGET):
    """Smallest-threshold operating point whose recall first reaches >= target (ranking-based)."""
    y = np.asarray(y, dtype=np.int64)
    s = np.asarray(s, dtype=np.float64)
    n_pos = int(y.sum())
    order = np.argsort(-s, kind="stable")
    cum = np.cumsum(y[order])
    need = int(np.ceil(target * n_pos - 1e-9))
    idx = int(np.searchsorted(cum, need, side="left"))
    thr = float(s[order][idx]) if idx < len(order) else float(np.min(s))
    return metrics_at(y, s, thr)


def sweep_pct(y, s, qs=QS):
    """precision/recall/f1 as a function of the score percentile q (0..100).

    threshold at percentile q = np.percentile(s, q); predicted positive = s >= threshold.
    q=0 -> threshold = min -> predict everything positive (recall 1).
    q=100 -> threshold = max -> predict only the maximum-scoring point(s)."""
    y = np.asarray(y, dtype=np.int64)
    s = np.asarray(s, dtype=np.float64)
    n_pos = int(y.sum())
    prec = np.empty(len(qs))
    rec = np.empty(len(qs))
    f1 = np.empty(len(qs))
    for i, q in enumerate(qs):
        t = float(np.percentile(s, q))
        pred = s >= t
        tp = int((pred & (y == 1)).sum())
        fp = int((pred & (y == 0)).sum())
        p = (tp / (tp + fp)) if (tp + fp) > 0 else np.nan
        r = tp / n_pos if n_pos > 0 else np.nan
        prec[i] = p
        rec[i] = r
        f1[i] = (2 * p * r / (p + r)) if (np.isfinite(p) and np.isfinite(r) and (p + r) > 0) else np.nan
    return prec, rec, f1


def pct_of_value(s, v):
    """Where a raw score value v sits on the percentile axis of s (0..100)."""
    s = np.asarray(s, dtype=np.float64)
    return float(100.0 * np.mean(s <= v))


# ------------------------------------------------------------------ data
def load_raw(emb_dir):
    import pandas as pd
    raw = {}
    for lg in PAIR:
        tr = pd.read_parquet(os.path.join(DATA_DIR, "%s_train.parquet" % lg))
        va = pd.read_parquet(os.path.join(DATA_DIR, "%s_validation.parquet" % lg))
        te = pd.read_parquet(os.path.join(DATA_DIR, "%s_test.parquet" % lg))
        raw[lg] = {}
        for split, df in (("train", tr), ("validation", va), ("test", te)):
            e = np.load(os.path.join(emb_dir, "emb_%s_%s.npy" % (lg, split)))
            e = np.ascontiguousarray(e, dtype=np.float32)
            assert e.shape[0] == len(df), "%s/%s row mismatch %d vs %d" % (
                emb_dir, split, e.shape[0], len(df))
            raw[lg][split] = (e, df["is_toxic"].astype(int).to_numpy())
    return raw


# ------------------------------------------------------------------ one (model, backbone)
def run_model_backbone(meta, emb_dir, name, bb, smoke=False):
    raw = load_raw(emb_dir)
    if smoke:
        for lg in PAIR:
            for split in ("train", "validation", "test"):
                e, y = raw[lg][split]
                k = min(len(y), 200)
                raw[lg][split] = (e[:k], y[:k])

    kind = meta["score"]
    clfs, train_y, vthr_raw, vthr_q, info = {}, {}, {}, {}, {}
    for lg in PAIR:
        Xtr, ytr = raw[lg]["train"]
        Xva, yva = raw[lg]["validation"]
        clf = meta["make"]()
        clf.fit(Xtr, ytr)
        clfs[lg] = clf
        train_y[lg] = ytr
        sv = decision_score(clf, Xva, kind, ytr=ytr)
        vthr_raw[lg], vthr_q[lg] = f1_opt_threshold(yva, sv)
        info[lg] = {"n_train": int(len(ytr)), "n_val": int(len(yva)),
                    "n_test": int(len(raw[lg]["test"][1])),
                    "n_pos_test": int(raw[lg]["test"][1].sum()),
                    "val_threshold_raw": float(vthr_raw[lg]),
                    "val_threshold_pct_val": int(vthr_q[lg]),
                    "score_kind": kind, "dim": int(Xtr.shape[1])}
        log("    %-22s %-4s %s trained (dim=%d) val_f1-opt raw-thr=%.4f (val pct=%d)"
            % (name, bb, lg, info[lg]["dim"], vthr_raw[lg], vthr_q[lg]))

    cells = {}
    for ml in PAIR:
        for tl in PAIR:
            key = "%s_model_on_%s" % (ml, tl)
            Xte, yte = raw[tl]["test"]
            s = decision_score(clfs[ml], Xte, kind, ytr=train_y[ml])
            prec, rec, f1 = sweep_pct(yte, s)
            val_pct = pct_of_value(s, vthr_raw[ml])
            cells[key] = {
                "model_lang": ml, "test_lang": tl, "score_kind": kind,
                "n_test": int(len(yte)), "n_pos_test": int(yte.sum()),
                "auc": auc_at(yte, s),
                "val_thr": metrics_at(yte, s, vthr_raw[ml]),
                "val_thr_pct": val_pct,
                "recall90": at_recall(yte, s, RECALL_TARGET),
                "score_stats": {"min": float(np.min(s)), "max": float(np.max(s)),
                                "median": float(np.median(s)), "n_unique": int(len(np.unique(s)))},
                "pct_grid": {"%d" % q: metrics_at(yte, s, float(np.percentile(s, q)))
                             for q in PCT_GRID},
                "curve": {
                    "q": [int(q) for q in QS],
                    "precision": [None if not np.isfinite(v) else round(float(v), 5) for v in prec],
                    "recall": [None if not np.isfinite(v) else round(float(v), 5) for v in rec],
                    "f1": [None if not np.isfinite(v) else round(float(v), 5) for v in f1],
                },
            }
            log("    %-22s %-4s %-18s auc=%.3f P@R90=%.3f val_pct=%.1f n_unique=%d"
                % (name, bb, key, cells[key]["auc"] or -1,
                   cells[key]["recall90"]["precision"], val_pct,
                   cells[key]["score_stats"]["n_unique"]))
    return cells, info


# ------------------------------------------------------------------ per-model 2x2 plot
def plot_model(all_cells, name, out_png):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    layout = {
        (0, 0): ("precision", ["en_model_on_en"]),
        (0, 1): ("precision", ["en_model_on_it", "it_model_on_it"]),
        (1, 0): ("recall", ["en_model_on_en"]),
        (1, 1): ("recall", ["en_model_on_it", "it_model_on_it"]),
    }
    col_titles = {0: "EN model / EN test",
                  1: "EN model / IT test  +  IT model / IT test"}
    fig, axes = plt.subplots(2, 2, figsize=(13, 8.6), sharex=True, sharey="row")

    for (r, c), (metric, names) in layout.items():
        ax = axes[r, c]
        for nm in names:
            color = CELL_COLORS[nm]
            for bbi in BACKBONES:
                cell = all_cells[bbi][nm]
                if cell is None:
                    continue
                x = np.array(cell["curve"]["q"], dtype=np.float64)
                arr = np.array([np.nan if v is None else v
                                for v in cell["curve"][metric]], dtype=np.float64)
                ax.plot(x, arr, color=color, lw=2.2, alpha=0.95, ls=BB_STYLE[bbi]["ls"])
                vq = cell["val_thr_pct"]
                j = int(np.argmin(np.abs(x - vq)))
                if np.isfinite(arr[j]):
                    ax.plot([vq], [arr[j]], marker=("o" if bbi == "210m" else "s"), ms=8,
                            mfc="white", mec=color, mew=1.8, zorder=6)
                ax.axvline(vq, color=color, ls=(":" if bbi == "610m" else "-"),
                           lw=1.0, alpha=0.28, zorder=1)
        ax.set_title("%s vs decision-score percentile\n%s" % (metric.capitalize(), col_titles[c]),
                     fontsize=10.5)
        ax.grid(alpha=0.25)
        ax.set_xlim(0, 100)
        ax.set_ylim(0, 1.03)

        handles = [Line2D([], [], color=CELL_COLORS[n], lw=2.2, label=CELL_LABELS[n]) for n in names]
        handles += [Line2D([], [], color="black", lw=2.2, ls=BB_STYLE[bbi]["ls"],
                           label=BB_STYLE[bbi]["label"]) for bbi in BACKBONES]
        handles += [Line2D([], [], color="grey", marker="o", ls="none", mfc="white", mec="grey",
                           mew=1.8, ms=8, label="val-tuned threshold (own val split)")]
        ax.legend(handles=handles, fontsize=9,
                  loc="upper right" if metric == "recall" else "lower right", framealpha=0.92)

    for c in (0, 1):
        axes[1, c].set_xlabel("decision-score percentile  q   (0 = predict all; higher = stricter)")
    for r in (0, 1):
        axes[r, 0].set_ylabel("precision" if r == 0 else "recall")

    fig.suptitle("toxi_pr_%s -- Precision (top) / Recall (bottom) vs decision-score percentile  --  "
                 "EuroBERT-210m (solid) vs 610m (dotted), RAW mean embeddings\n"
                 "left = EN model / EN test;  right = EN model / IT test + IT model / IT test;  "
                 "circles/squares = each model's own val-tuned F1-optimal threshold" % name,
                 fontsize=11)
    fig.tight_layout(rect=[0, 0, 1, 0.92])
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
