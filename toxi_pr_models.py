# ------------------------------------------------------------------ classifier zoo
def build_zoo():
    from sklearn.svm import LinearSVC
    from sklearn.linear_model import LogisticRegression
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.neighbors import KNeighborsClassifier
    from sklearn.neural_network import MLPClassifier
    from sklearn.naive_bayes import GaussianNB

    # ordered exactly as requested; score = "proba" | "sigmoid"
    zoo = {
        "SVC_linear": dict(
            score="sigmoid",
            make=lambda: LinearSVC(C=1.0, loss="squared_hinge", dual=False, max_iter=20000),
            note="liblinear PRIMAL linear SVM (fast equivalent of SVC(kernel='linear')); "
                 "sigmoid(decision_function) -> [0,1]"),
        "MLPClassifier": dict(
            score="proba",
            make=lambda: MLPClassifier(random_state=SEED, max_iter=300),
            note="sklearn defaults (hidden=(100,), max_iter=300)"),
        "LogisticRegression": dict(
            score="proba",
            make=lambda: LogisticRegression(max_iter=2000, n_jobs=N_JOBS),
            note="max_iter=2000"),
        "RandomForestClassifier": dict(
            score="proba",
            make=lambda: RandomForestClassifier(n_estimators=200, random_state=SEED, n_jobs=N_JOBS),
            note="n_estimators=200 (sklearn max_features='sqrt'), n_jobs=2"),
        "KNeighborsClassifier": dict(
            score="proba",
            make=lambda: KNeighborsClassifier(n_jobs=N_JOBS),
            note="k=5 (default), n_jobs=2"),
        "GaussianNB": dict(
            score="proba",
            make=lambda: GaussianNB(),
            note="sklearn defaults"),
    }
    return zoo


# ------------------------------------------------------------------ transforms / metrics
def scores_of(clf, X, kind):
    if kind == "sigmoid":
        d = np.asarray(clf.decision_function(X), dtype=np.float64).ravel()
        return 1.0 / (1.0 + np.exp(-d))
    P = np.asarray(clf.predict_proba(X), dtype=np.float64)
    return P[:, 1]


def metrics_at(y, s, thr):
    y = np.asarray(y, dtype=np.int64)
    pred = (np.asarray(s, dtype=np.float64) >= thr).astype(np.int64)
    tp = int(((pred == 1) & (y == 1)).sum())
    fp = int(((pred == 1) & (y == 0)).sum())
    fn = int(((pred == 0) & (y == 1)).sum())
    tn = int(((pred == 0) & (y == 0)).sum())
    prec = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    rec = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2.0 * prec * rec / (prec + rec) if (prec + rec) > 0 else 0.0
    return {"threshold": float(thr), "precision": float(prec), "recall": float(rec),
            "f1": float(f1), "TP": tp, "FP": fp, "FN": fn, "TN": tn}


def auc_at(y, s):
    from sklearn.metrics import roc_auc_score
    y = np.asarray(y, dtype=np.int64)
    if y.sum() == 0 or y.sum() == len(y):
        return None
    return float(roc_auc_score(y, s))


def f1_opt_threshold(y, s):
    from sklearn.metrics import f1_score
    best_t, best_f = 0.5, -1.0
    for t in THR_SWEEP:
        f = f1_score(y, (s >= t).astype(int), zero_division=0)
        if f > best_f:
            best_f, best_t = float(f), float(t)
    return best_t


def at_recall(y, s, target=RECALL_TARGET):
    """Smallest-threshold operating point whose recall first reaches >= target."""
    y = np.asarray(y, dtype=np.int64)
    s = np.asarray(s, dtype=np.float64)
    n_pos = int(y.sum())
    order = np.argsort(-s, kind="stable")
    cum = np.cumsum(y[order])
    need = int(np.ceil(target * n_pos - 1e-9))
    idx = int(np.searchsorted(cum, need, side="left"))
    thr = float(s[order][idx]) if idx < len(order) else float(np.min(s))
    return metrics_at(y, s, thr)


def sweep(y, s, grid):
    y = np.asarray(y, dtype=np.int64)
    s = np.asarray(s, dtype=np.float64)
    n_pos = int(y.sum())
    prec = np.empty(len(grid))
    rec = np.empty(len(grid))
    f1 = np.empty(len(grid))
    for i, t in enumerate(grid):
        pred = s >= t
        tp = int((pred & (y == 1)).sum())
        fp = int((pred & (y == 0)).sum())
        p = (tp / (tp + fp)) if (tp + fp) > 0 else np.nan
        r = tp / n_pos if n_pos > 0 else np.nan
        prec[i] = p
        rec[i] = r
        f1[i] = (2 * p * r / (p + r)) if (np.isfinite(p) and np.isfinite(r) and (p + r) > 0) else np.nan
    return prec, rec, f1


# ------------------------------------------------------------------ data
def load_raw(emb_dir):
    import pandas as pd
    raw = {}
    for lg in PAIR:
        tr = pd.read_parquet(os.path.join(DATA_DIR, "%s_train.parquet" % lg))
        va = pd.read_parquet(os.path.join(DATA_DIR, "%s_validation.parquet" % lg))
        te = pd.read_parquet(os.path.join(DATA_DIR, "%s_test.parquet" % lg))
        raw[lg] = {}
        for split, df in (("train", tr), ("validation", va), ("test", te)):
            e = np.load(os.path.join(emb_dir, "emb_%s_%s.npy" % (lg, split)))
            e = np.ascontiguousarray(e, dtype=np.float32)
            assert e.shape[0] == len(df), "%s/%s row mismatch %d vs %d" % (
                emb_dir, split, e.shape[0], len(df))
            raw[lg][split] = (e, df["is_toxic"].astype(int).to_numpy())
    return raw


# ------------------------------------------------------------------ one (model, backbone)
def run_model_backbone(meta, emb_dir, name, bb, smoke=False):
    raw = load_raw(emb_dir)
    if smoke:
        for lg in PAIR:
            for split in ("train", "validation", "test"):
                e, y = raw[lg][split]
                k = min(len(y), 200)
                raw[lg][split] = (e[:k], y[:k])

    clfs, vthr, info = {}, {}, {}
    for lg in PAIR:
        Xtr, ytr = raw[lg]["train"]
        Xva, yva = raw[lg]["validation"]
        clf = meta["make"]()
        clf.fit(Xtr, ytr)
        clfs[lg] = clf
        sv = scores_of(clf, Xva, meta["score"])
        vthr[lg] = f1_opt_threshold(yva, sv)
        info[lg] = {"n_train": int(len(ytr)), "n_val": int(len(yva)),
                    "n_test": int(len(raw[lg]["test"][1])),
                    "n_pos_test": int(raw[lg]["test"][1].sum()),
                    "val_threshold": float(vthr[lg]),
                    "dim": int(Xtr.shape[1])}
        log("    %-22s %-4s %s trained (dim=%d) val_f1-opt thr=%.3f"
            % (name, bb, lg, info[lg]["dim"], vthr[lg]))

    cells = {}
    for ml in PAIR:
        for tl in PAIR:
            key = "%s_model_on_%s" % (ml, tl)
            Xte, yte = raw[tl]["test"]
            s = scores_of(clfs[ml], Xte, meta["score"])
            prec, rec, f1 = sweep(yte, s, THR_SWEEP)
            cells[key] = {
                "model_lang": ml, "test_lang": tl,
                "n_test": int(len(yte)), "n_pos_test": int(yte.sum()),
                "auc": auc_at(yte, s),
                "val_thr": metrics_at(yte, s, vthr[ml]),
                "recall90": at_recall(yte, s, RECALL_TARGET),
                "grid": {("%.1f" % t): metrics_at(yte, s, t) for t in THR_GRID},
                "curve": {
                    "threshold": [float(t) for t in THR_SWEEP],
                    "precision": [None if not np.isfinite(v) else round(float(v), 5) for v in prec],
                    "recall": [None if not np.isfinite(v) else round(float(v), 5) for v in rec],
                    "f1": [None if not np.isfinite(v) else round(float(v), 5) for v in f1],
                },
            }
            log("    %-22s %-4s %-18s auc=%.3f P@R90=%.3f (EN-IT=%s IT-IT=%s)"
                % (name, bb, key, cells[key]["auc"] or -1,
                   cells[key]["recall90"]["precision"], ml == "en", tl == "it"))
    return cells, info


# ------------------------------------------------------------------ per-model 2x2 plot
def plot_model(all_cells, name, out_png):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    layout = {
        (0, 0): ("precision", ["en_model_on_en"]),
        (0, 1): ("precision", ["en_model_on_it", "it_model_on_it"]),
        (1, 0): ("recall", ["en_model_on_en"]),
        (1, 1): ("recall", ["en_model_on_it", "it_model_on_it"]),
    }
    col_titles = {0: "EN model / EN test",
                  1: "EN model / IT test  +  IT model / IT test"}
    fig, axes = plt.subplots(2, 2, figsize=(13, 8.6), sharex=True, sharey="row")

    for (r, c), (metric, names) in layout.items():
        ax = axes[r, c]
        for nm in names:
            color = CELL_COLORS[nm]
            for bb in BACKBONES:
                cell = all_cells[bb][nm]
                x = np.array(cell["curve"]["threshold"])
                arr = np.array([np.nan if v is None else v
                                for v in cell["curve"][metric]], dtype=np.float64)
                ax.plot(x, arr, color=color, lw=2.2, alpha=0.95, ls=BB_STYLE[bb]["ls"])
                vt = cell["val_thr"]["threshold"]
                j = int(np.argmin(np.abs(x - vt)))
                if np.isfinite(arr[j]):
                    ax.plot([vt], [arr[j]], marker=("o" if bb == "210m" else "s"), ms=8,
                            mfc="white", mec=color, mew=1.8, zorder=6)
                ax.axvline(vt, color=color, ls=(":" if bb == "610m" else "-"),
                           lw=1.0, alpha=0.28, zorder=1)
        ax.set_title("%s vs threshold\n%s" % (metric.capitalize(), col_titles[c]), fontsize=10.5)
        ax.grid(alpha=0.25)
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1.03)

        handles = [Line2D([], [], color=CELL_COLORS[n], lw=2.2, label=CELL_LABELS[n]) for n in names]
        handles += [Line2D([], [], color="black", lw=2.2, ls=BB_STYLE[bb]["ls"],
                           label=BB_STYLE[bb]["label"]) for bb in BACKBONES]
        handles += [Line2D([], [], color="grey", marker="o", ls="none", mfc="white", mec="grey",
                           mew=1.8, ms=8, label="val-tuned threshold")]
        ax.legend(handles=handles, fontsize=9,
                  loc="upper right" if metric == "recall" else "lower right", framealpha=0.92)

    for c in (0, 1):
        axes[1, c].set_xlabel("decision threshold  t")
    for r in (0, 1):
        axes[r, 0].set_ylabel("precision" if r == 0 else "recall")

    fig.suptitle("toxi_pr_%s -- Precision (top) / Recall (bottom) vs threshold  --  "
                 "EuroBERT-210m (solid) vs 610m (dotted), RAW mean embeddings\n"
                 "left = EN model / EN test;  right = EN model / IT test + IT model / IT test;  "
                 "circles/squares = each model's own val-tuned F1-optimal threshold" % name,
                 fontsize=11)
    fig.tight_layout(rect=[0, 0, 1, 0.92])
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    log("wrote %s" % out_png)


# ------------------------------------------------------------------ combined grid (models x backbones)
def plot_grid(results, model_order, out_png):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    nrow, ncol = len(model_order), len(BACKBONES)
    fig, axes = plt.subplots(nrow, ncol, figsize=(12.5, 2.9 * nrow),
                             sharex=True, sharey=True, squeeze=False)
    names = ["en_model_on_en", "en_model_on_it", "it_model_on_it"]

    for i, name in enumerate(model_order):
        for j, bb in enumerate(BACKBONES):
            ax = axes[i, j]
            cells = results.get(name, {}).get(bb)
            if cells is None:
                ax.set_axis_off()
                ax.text(0.5, 0.5, "%s / %s\n(failed)" % (name, bb), ha="center", va="center")
                continue
            for nm in names:
                cell = cells[nm]
                x = np.array(cell["curve"]["threshold"])
                f1 = np.array([np.nan if v is None else v for v in cell["curve"]["f1"]],
                              dtype=np.float64)
                ax.plot(x, f1, color=CELL_COLORS[nm], lw=1.9, alpha=0.95)
                vt = cell["val_thr"]["threshold"]
                jj = int(np.argmin(np.abs(x - vt)))
                if np.isfinite(f1[jj]):
                    ax.plot([vt], [f1[jj]], marker="o", ms=6, mfc="white",
                            mec=CELL_COLORS[nm], mew=1.6, zorder=6)
            ax.grid(alpha=0.25)
            ax.set_ylim(0, 1.03)
            ax.set_xlim(0, 1)
            if i == 0:
                ax.set_title("EuroBERT-%s (%s)" % (bb, "solid" if bb == "210m" else "dotted"),
                             fontsize=11)
            if j == 0:
                ax.set_ylabel("F1\n%s" % name, fontsize=9.0)
            if i == nrow - 1:
                ax.set_xlabel("decision threshold  t")

    handles = [Line2D([], [], color=CELL_COLORS[n], lw=2.0, label=CELL_LABELS[n]) for n in names]
    handles += [Line2D([], [], color="grey", marker="o", ls="none", mfc="white", mec="grey",
                       mew=1.6, ms=6, label="val-tuned threshold")]
    fig.legend(handles=handles, fontsize=9.5, loc="lower center", ncol=4,
               framealpha=0.92, bbox_to_anchor=(0.5, 0.0))
    fig.suptitle("toxi_pr_models_grid -- F1 vs threshold  (rows = classifier, cols = backbone)\n"
                 "raw mean embeddings;  EN model / EN test,  EN model / IT test,  IT model / IT test",
                 fontsize=12)
    fig.tight_layout(rect=[0, 0.03, 1, 0.965])
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    log("wrote %s" % out_png)


# ------------------------------------------------------------------ report
def _fmt(v, nd=3):
    return "n/a" if v is None else ("%.*f" % (nd, v))


