# ------------------------------------------------- combined grid (models x backbones), one metric
def plot_grid(results, model_order, out_png, metric):
    """One grid for ONE metric: rows = classifier, cols = backbone.

    Each cell overlays EN-on-EN / EN-on-IT / IT-on-IT for `metric` ("precision" or "recall")
    vs the decision-score percentile q.  Emitted as two separate figures (precision, recall) so
    the deliverable is explicitly Precision and Recall, never F1 (see module docstring)."""
    assert metric in ("precision", "recall"), metric
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    nrow, ncol = len(model_order), len(BACKBONES)
    fig, axes = plt.subplots(nrow, ncol, figsize=(12.5, 3.0 * nrow),
                             sharex=True, sharey=True, squeeze=False)
    names = ["en_model_on_en", "en_model_on_it", "it_model_on_it"]

    for i, name in enumerate(model_order):
        for j, bbi in enumerate(BACKBONES):
            ax = axes[i, j]
            cells = results.get(name, {}).get(bbi)
            if cells is None:
                ax.set_axis_off()
                ax.text(0.5, 0.5, "%s / %s\n(failed)" % (name, bbi), ha="center", va="center")
                continue
            for nm in names:
                cell = cells[nm]
                x = np.array(cell["curve"]["q"], dtype=np.float64)
                arr = np.array([np.nan if v is None else v for v in cell["curve"][metric]],
                               dtype=np.float64)
                ax.plot(x, arr, color=CELL_COLORS[nm], lw=1.9, alpha=0.95, ls="-")
                vq = cell["val_thr_pct"]
                jj = int(np.argmin(np.abs(x - vq)))
                if np.isfinite(arr[jj]):
                    ax.plot([vq], [arr[jj]], marker="o", ms=6, mfc="white",
                            mec=CELL_COLORS[nm], mew=1.6, zorder=6)
                ax.axvline(vq, color=CELL_COLORS[nm], ls=":", lw=0.9, alpha=0.22, zorder=1)
            ax.grid(alpha=0.25)
            ax.set_ylim(0, 1.03)
            ax.set_xlim(0, 100)
            if i == 0:
                ax.set_title("EuroBERT-%s" % bbi, fontsize=11)
            if j == 0:
                ax.set_ylabel("%s\n%s" % (name, metric), fontsize=8.6)
            if i == nrow - 1:
                ax.set_xlabel("score percentile  q")

    handles = [Line2D([], [], color=CELL_COLORS[n], lw=2.0, label=CELL_LABELS[n]) for n in names]
    handles += [Line2D([], [], color="grey", marker="o", ls="none", mfc="white", mec="grey",
                       mew=1.5, ms=6, label="val-tuned threshold")]
    fig.legend(handles=handles, fontsize=9.5, loc="lower center", ncol=4,
               framealpha=0.92, bbox_to_anchor=(0.5, 0.0))
    fig.suptitle("toxi_pr_models_grid_%s -- %s vs decision-score percentile  "
                 "(rows = classifier, cols = backbone)\n"
                 "raw mean embeddings;  colour = EN model / EN test,  EN model / IT test,  "
                 "IT model / IT test;  val marker = own-language F1-optimal threshold"
                 % (metric, metric.capitalize()), fontsize=11)
    fig.tight_layout(rect=[0, 0.03, 1, 0.965])
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    log("wrote %s" % out_png)


