# ------------------------------------------------------------------ report
def _fmt(v, nd=3):
    return "n/a" if v is None else ("%.*f" % (nd, v))


def write_reports(payload, results, model_order):
    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)
    log("wrote %s" % OUT_JSON)

    L = []
    A = L.append
    A("# toxi_pr_models -- precision/recall vs decision-score percentile for NON-XGBoost classifiers\n")
    A("Same toxicity task and figure layout as `toxi_pr.png` (XGBoost), swapped detector. "
      "Data `data/toxi_clean/`, **RAW mean** embeddings `emb_bf16/toxic/{210m,610m}/emb_"
      "<lang>_<split>.npy` (**no `perlang_z`** -- chosen to match the raw fine-tune convention "
      "and keep it simple). `210m` = solid, `610m` = dotted. Val threshold = F1-optimal on the "
      "model's own-language validation split.\n")
    A("**Sweep axis = decision-score percentile q (0..100), not raw probability 0..1.** The old "
      "raw-probability sweep was invalid for `GaussianNB` (saturated `predict_proba`, F1-opt val "
      "threshold at 0.99-1.00) and `KNeighborsClassifier` (k=5 -> only 6 discrete probabilities). "
      "Each model now uses a monotone, continuous decision score (see `toxi_pr_models.py` "
      "docstring): `SVC_linear`/`LogisticRegression` = `decision_function`; `MLP`/`RF` = "
      "`predict_proba[:,1]`; `GaussianNB` = log-likelihood-ratio; `KNN` = continuous "
      "distance-weighted positive fraction. `SVC_linear` uses the liblinear PRIMAL linear SVM "
      "(`LinearSVC(loss='squared_hinge', dual=False)`) -- plain libsvm `SVC(kernel='linear')` was "
      "infeasible at n=24k x 768 (>11 min/fit, non-convergent).\n")
    A("")
    A("## P@recall=0.90 (EN-on-IT and IT-on-IT) and AUC, per model x backbone\n")
    A("`gap` = |P(EN/IT) - P(IT/IT)| at recall 0.90 (smaller = EN-on-IT closer to IT-on-IT). "
      "AUC and P@R90 are ranking-based (invariant to the monotone score rescaling); for KNN the "
      "score function itself changed (discrete fraction -> continuous distance-weighted fraction), "
      "so its AUC/P@R90 are recomputed.\n")
    A("| model | backbone | AUC EN/EN | AUC EN/IT | AUC IT/IT | "
      "P@R90 EN/EN | P@R90 EN/IT | P@R90 IT/IT | gap |")
    A("|---|---|---|---|---|---|---|---|---|")
    for name in model_order:
        for bbi in BACKBONES:
            cells = results.get(name, {}).get(bbi)
            if cells is None:
                A("| %s | %s | n/a | n/a | n/a | n/a | n/a | n/a | n/a |" % (name, bbi))
                continue
            ee = cells["en_model_on_en"]
            ei = cells["en_model_on_it"]
            ii = cells["it_model_on_it"]
            gap = abs(ei["recall90"]["precision"] - ii["recall90"]["precision"])
            A("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                name, bbi, _fmt(ee["auc"]), _fmt(ei["auc"]), _fmt(ii["auc"]),
                _fmt(ee["recall90"]["precision"]), _fmt(ei["recall90"]["precision"]),
                _fmt(ii["recall90"]["precision"]), _fmt(gap)))
    A("")
    A("## Closest EN-on-IT to IT-on-IT @ recall 0.90 (per backbone)\n")
    for bbi in BACKBONES:
        ranked = []
        for name in model_order:
            cells = results.get(name, {}).get(bbi)
            if cells is None:
                continue
            ei = cells["en_model_on_it"]["recall90"]["precision"]
            ii = cells["it_model_on_it"]["recall90"]["precision"]
            ranked.append((abs(ei - ii), name, ei, ii))
        ranked.sort()
        A("**%s**: " % bbi + ", ".join(
            "`%s` (gap %.3f; EN/IT %.3f vs IT/IT %.3f)" % (n, g, ei, ii)
            for g, n, ei, ii in ranked))
        A("")
    A("## Grid figure paths (rows=models, cols={210m,610m}; vs decision-score percentile)\n")
    A("* `toxi_pr_models_grid.png` -- ONE combined grid: rows = classifier x {Precision, Recall} "
      "(14 rows for 7 classifiers), cols = backbone")
    A("* `toxi_pr_models_grid_precision.png` -- Precision only, overlaying EN-on-EN / EN-on-IT / IT-on-IT")
    A("* `toxi_pr_models_grid_recall.png` -- Recall only, overlaying EN-on-EN / EN-on-IT / IT-on-IT")
    A("")
    A("## Per-model figure paths\n")
    for name in model_order:
        A("* `toxi_pr_%s.png`" % name)
    A("")
    with open(OUT_MD, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    log("wrote %s" % OUT_MD)


# ------------------------------------------------------------------ detached launch
def launch_detached(passthrough):
    vbs = os.path.join(REPO, "launch_hidden.vbs")
    cmd = subprocess.list2cmdline([sys.executable, os.path.abspath(__file__)] + passthrough)
    subprocess.Popen(["wscript", "//B", "//Nologo", vbs, cmd],
                     cwd=REPO, creationflags=0x08000000)


# ------------------------------------------------------------------ main
def parse_args(argv):
    ap = argparse.ArgumentParser(description="Non-XGBoost precision/recall 2x2 on toxicity")
    ap.add_argument("--launch", action="store_true", help="spawn detached via launch_hidden.vbs")
    ap.add_argument("--backbone", default="both",
                    help="comma-separated subset of {210m,610m} or 'both' (default)")
    ap.add_argument("--only", default="", help="comma-separated classifier names to run")
    ap.add_argument("--smoke", action="store_true", help="tiny plumbing check (TEMP outputs)")
    ap.add_argument("--figures-only", action="store_true",
                    help="re-plot figures from an existing toxi_pr_models.json (no refit)")
    return ap.parse_args(argv)


def figures_only():
    """Re-plot from the existing JSON payload (no model refit)."""
    with open(OUT_JSON, "r", encoding="utf-8") as f:
        payload = json.load(f)
    results = payload["results"]
    model_order = [n for n in ("XGBoost", "SVC_linear", "MLPClassifier", "LogisticRegression",
                               "RandomForestClassifier", "KNeighborsClassifier", "GaussianNB")
                   if n in results]
    for name in model_order:
        try:
            if all(results.get(name, {}).get(b) is None for b in BACKBONES):
                continue
            plot_model({b: results[name][b] for b in BACKBONES}, name,
                       os.path.join(REPO, "toxi_pr_%s.png" % name))
        except Exception as exc:                              # noqa: BLE001
            log("per-model plot failed for %s: %r" % (name, exc))
    plot_grids(results, model_order)
    return 0


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    args = parse_args(argv)
    if args.launch:
        launch_detached([a for a in argv if a != "--launch"])
        print("launched detached via launch_hidden.vbs")
        return 0
    if args.figures_only:
        return figures_only()

    if args.backbone == "both":
        backbones = list(BACKBONES)
    else:
        backbones = [b.strip() for b in args.backbone.split(",") if b.strip()]
        bad = [b for b in backbones if b not in BACKBONES]
        if bad:
            raise SystemExit("unknown backbone(s) %s; known {210m,610m}" % bad)

    zoo = build_zoo()
    order = list(zoo.keys())
    if args.only:
        want = [m.strip() for m in args.only.split(",") if m.strip()]
        unknown = [m for m in want if m not in order]
        if unknown:
            raise SystemExit("unknown model(s) %s; known %s" % (unknown, order))
        model_order = want
    else:
        model_order = order

    out_json, out_md = OUT_JSON, OUT_MD

    # Load any previously computed results so that `--only <model>` ADDS a model instead of
    # clobbering the others (the freshly-run models always win; the rest are carried over).
    existing = {}
    if not args.smoke and os.path.exists(out_json):
        try:
            with open(out_json, "r", encoding="utf-8") as f:
                existing = json.load(f).get("results", {}) or {}
        except Exception:
            existing = {}

    def merged_snapshot():
        snap = {}
        for n in order:
            fresh = results.get(n)
            if fresh and any(fresh.get(b) for b in BACKBONES):
                snap[n] = fresh
            elif n in existing and any(existing[n].get(b) for b in BACKBONES):
                snap[n] = existing[n]
        return snap

    try:
        if os.path.exists(LOG_PATH) and not args.smoke:
            os.remove(LOG_PATH)
    except Exception:
        pass

    if not args.smoke:
        write_pid()
    state = {"phase": "start", "pid": os.getpid(), "backbones": backbones,
             "models": model_order, "smoke": bool(args.smoke)}
    write_status(state)

    log("toxi_pr_models starting: backbones=%s models=%s smoke=%s"
        % (backbones, model_order, args.smoke))

    results = {}
    for name in model_order:
        results[name] = {}
        for bbi in backbones:
            state["phase"] = "model:%s/%s" % (name, bbi)
            write_status(state)
            ts = time.time()
            try:
                cells, info = run_model_backbone(zoo[name], BB_DIRS[bbi], name, bbi, smoke=args.smoke)
                results[name][bbi] = cells
                results[name].setdefault("_info", {})[bbi] = info
                log("  DONE %-22s %-4s (%.1fs)" % (name, bbi, time.time() - ts))
            except Exception as exc:                          # noqa: BLE001
                log("  FAILED %-22s %-4s: %r" % (name, bbi, exc))
                results[name][bbi] = None
            # incremental save (merged with previously stored models, so --only never clobbers)
            try:
                with open(out_json if not args.smoke else out_json + ".smoke", "w",
                          encoding="utf-8") as f:
                    json.dump({"results": merged_snapshot()}, f, indent=2)
            except Exception:
                pass

    merged = merged_snapshot()
    report_order = [n for n in order if n in merged]

    payload = {
        "config": {
            "data_dir": "data/toxi_clean",
            "emb_root": "emb_bf16/toxic",
            "backbones": {"210m": "emb_bf16/toxic/210m (solid in per-model figures)",
                          "610m": "emb_bf16/toxic/610m (dotted in per-model figures)"},
            "pooling": "mean",
            "features": "RAW mean embeddings (NO perlang_z / no L2 / no z-score)",
            "sweep_axis": "decision-score percentile q=0..100 (see decision_score kinds); "
                          "0 = predict all positive, larger q = stricter",
            "pct_grid": PCT_GRID,
            "classifiers": {n: {"score_kind": zoo[n]["score"], "note": zoo[n]["note"]}
                            for n in report_order if n in zoo},
            "recall_target": RECALL_TARGET,
            "val_threshold_rule": "F1-optimal on the model's own-language validation split, searched "
                                  "over the validation score's percentiles (raw threshold stored)",
            "svc_linear_note": "plain libsvm SVC(kernel='linear') is infeasible at n=24k x 768 "
                               "(>11 min/fit, non-convergent); used the liblinear PRIMAL linear "
                               "SVM LinearSVC(loss='squared_hinge', dual=False) as its fast "
                               "equivalent, scored by decision_function.",
            "note": "210m curves are solid, 610m curves are dotted in the per-model figures. "
                    "The deliverable grids are two separate figures (Precision and Recall), each "
                    "with columns = backbones, so within-cell solid/dotted is meaningless there.",
            "grid_figures": ["toxi_pr_models_grid.png",
                             "toxi_pr_models_grid_precision.png",
                             "toxi_pr_models_grid_recall.png"],
        },
        "results": merged,
        "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
    }

    if args.smoke:
        sm = OUT_JSON.replace(".json", "_smoke.json")
        with open(sm, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)
        log("SMOKE wrote %s" % sm)
        state["phase"] = "done"
        write_status(state)
        return 0

    write_reports(payload, merged, report_order)

    # per-model 2x2 figures
    for name in report_order:
        try:
            if all(merged.get(name, {}).get(bbi) is None for bbi in backbones):
                log("skip figure %s (no cells)" % name)
                continue
            plot_model({bbi: merged[name][bbi] for bbi in backbones}, name,
                       os.path.join(REPO, "toxi_pr_%s.png" % name))
        except Exception as exc:                              # noqa: BLE001
            log("per-model plot failed for %s: %r" % (name, exc))

    # deliverable grids: Precision and Recall, each as its own figure (no F1 grid)
    try:
        plot_grids(merged, report_order)
    except Exception as exc:                                  # noqa: BLE001
        log("grid plot failed: %r" % (exc,))

    state["phase"] = "done"
    state["elapsed_s"] = round(time.time() - _T0, 1)
    write_status(state)

    log("=" * 70)
    for bbi in backbones:
        ranked = []
        for name in report_order:
            cells = merged.get(name, {}).get(bbi)
            if not cells:
                continue
            ei = cells["en_model_on_it"]["recall90"]["precision"]
            ii = cells["it_model_on_it"]["recall90"]["precision"]
            ranked.append((abs(ei - ii), name, ei, ii))
        ranked.sort()
        log("closest EN/IT -> IT/IT @R90 [%s]: " % bbi + ", ".join(
            "%s(gap=%.3f)" % (n, g) for g, n, _, _ in ranked))
    log("ALL DONE in %.1fs" % (time.time() - _T0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
